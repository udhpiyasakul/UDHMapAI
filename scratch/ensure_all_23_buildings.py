import json

with open('map-data.json', encoding='utf-8') as f:
    data = json.load(f)

data['schemaVersion'] = '2.5.0'
data['hospital']['all23BuildingsComplete'] = True

# Helper to find or create building by mapNumber & id
def ensure_building(b_id, map_number, code, name, desc):
    b = next((item for item in data['buildings'] if item['id'] == b_id or item.get('mapNumber') == map_number), None)
    if not b:
        b = {
            "id": b_id,
            "mapNumber": map_number,
            "code": code,
            "name": name,
            "description": desc,
            "floors": []
        }
        data['buildings'].append(b)
    else:
        b['id'] = b_id
        b['mapNumber'] = map_number
        b['code'] = code
        b['name'] = name
        b['description'] = desc
        if not isinstance(b.get('floors'), list):
            b['floors'] = []
    return b

def ensure_floor(building, level, name=None, short_name=None):
    if not name:
        name = f"ชั้น {level}"
    if not short_name:
        short_name = f"ชั้น {level}"
    f = next((fl for fl in building['floors'] if fl['level'] == level), None)
    if not f:
        f_id = f"{building['id']}-f{level}"
        f = {
            "id": f_id,
            "level": level,
            "name": name,
            "shortName": short_name,
            "items": [],
            "routeNodes": [],
            "routeEdges": []
        }
        building['floors'].append(f)
    else:
        f['name'] = name
        f['shortName'] = short_name
        if not isinstance(f.get('items'), list): f['items'] = []
    return f

def add_room_item(floor, r_id, r_name, r_kind='room', r_cat='บริการผู้ป่วย', r_desc='', ext='', phone='', mobile='', x=15, y=15, w=25, h=18):
    items = floor['items']
    r = next((item for item in items if item['id'] == r_id or item['name'] == r_name), None)
    if not r:
        r = {
            "id": r_id,
            "kind": r_kind,
            "name": r_name,
            "category": r_cat,
            "description": r_desc,
            "extension": ext,
            "phone": phone or (f"042-245555 ต่อ {ext}" if ext else ""),
            "mobile": mobile,
            "x": x,
            "y": y,
            "w": w,
            "h": h,
            "facilityStatus": {
                "cleaningStatus": "clean",
                "cleaningStatusText": "🟢 ทำความสะอาด & ฆ่าเชื้อแล้ว",
                "lastCleanedTime": "เพิ่งทำความสะอาด",
                "openHours": "24 ชั่วโมง" if "ICU" in r_name or "ER" in r_name or "คลอด" in r_name else "08:00 - 16:30 น."
            }
        }
        items.append(r)
    else:
        r['name'] = r_name
        r['category'] = r_cat
        if r_desc: r['description'] = r_desc
        if ext: r['extension'] = ext
        if phone: r['phone'] = phone

